# create the below matrix A and B with python
# A = 1 2 3
#     4 5 6
#     7 8 9 
# 
# B = 1 2 1
#     6 2 3
#     4 2 1 
# Creating matrix A and B as standard Python lists
A = [
    [1, 2, 3],
    [4, 5, 6],
    [7, 8, 9]
]

B = [
    [1, 2, 1],
    [6, 2, 3],
    [4, 2, 1]
]
print("Matrix A:")

for row in A:
    print(row)

print("Matrix B:")

for row in B:
    print(row)
